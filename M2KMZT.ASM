; Standard 128-byte MZT header followed by a low-RAM relocation stub.
MZT_LOAD EQU 01200H
BODY_DEST EQU 08000H
BODY_ENTRY EQU 08080H
	ORG MZT_LOAD-128
MZT_HEADER:
	DB 1,"LD-MZ2000",0DH
	DS 18-($-MZT_HEADER)
	DW MZT_END-MZT_ENTRY,MZT_LOAD,MZT_LOAD
	DS 104
MZT_ENTRY:
	DI
	LD HL,BODY_SRC
	LD DE,BODY_DEST
	LD BC,BODY_SIZE
	LDIR
	JP BODY_ENTRY
BODY_SRC:
	INCLUDE "M2K.BIN", B
MZT_END:
BODY_SIZE EQU MZT_END-BODY_SRC
	END
