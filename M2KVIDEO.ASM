; All code and stack used while TVRAM is mapped must fit outside D000h-DFFFh.
M2K_TVRAM_SAFE_BEGIN:
M2K_MAP:
	IN A,(PIO_A)
	AND 03FH
	OR C
	OUT (PIO_A),A
	RET

M2K_VIDEO_BEGIN:
	DI
	LD (M2K_VIDEO_HL),HL
	POP HL
	LD (M2K_VIDEO_SP),SP
	LD SP,M2K_VIDEO_STACK_END
	PUSH HL
	LD HL,(M2K_VIDEO_HL)
	PUSH AF
	PUSH BC
	LD C,0C0H
	CALL M2K_MAP
	POP BC
	POP AF
	RET
M2K_VIDEO_END:
	PUSH AF
	PUSH BC
	LD C,0
	CALL M2K_MAP
	POP BC
	POP AF
	LD SP,(M2K_VIDEO_SP)
	RET
M2K_VIDEO_SP: DW 0
M2K_VIDEO_HL: DW 0

; _SCRN reads one display code given BC = absolute TVRAM address.
SCRN:
	CALL M2K_VIDEO_BEGIN
	LD A,(BC)
	JP M2K_VIDEO_END
M2K_PUT:
	CALL M2K_VIDEO_BEGIN
	LD (HL),A
	JP M2K_VIDEO_END
M2K_FILL:
	CALL M2K_VIDEO_BEGIN
M2K_FILL_LOOP:
	LD (HL),' '
	INC HL
	DEC BC
	LD A,B
	OR C
	JR NZ,M2K_FILL_LOOP
	JP M2K_VIDEO_END
M2K_SCROLL:
	PUSH DE
	CALL M2K_VIDEO_BEGIN
	LD HL,TVRAM+WIDTH
	LD DE,TVRAM
	LD BC,CELLS-WIDTH
	LDIR
	EX DE,HL
	LD BC,WIDTH
	JR M2K_SCROLL_CLEAR
M2K_SCROLL_CLEAR:
	LD (HL),' '
	INC HL
	DEC BC
	LD A,B
	OR C
	JR NZ,M2K_SCROLL_CLEAR
	CALL M2K_VIDEO_UNMAP
	POP DE
	RET
M2K_VIDEO_UNMAP:
	; The return address is still on the TVRAM-safe stack.
	LD C,0
	CALL M2K_MAP
	POP HL
	LD SP,(M2K_VIDEO_SP)
	JP (HL)

M2K_VIDEO_STACK: DS 32
M2K_VIDEO_STACK_END:
M2K_TVRAM_SAFE_END:
