; The console uses the common BDOS and CCP conventions.
_SYS04 EQU _ERROR
_SYS05 EQU _ERROR
_SYS1C EQU _ERROR
_SYS1E EQU _ERROR
_SYS20 EQU _ERROR
_SYS2E EQU _ERROR
INT EQU 0
INTCTCE EQU 0
INTCTC2 EQU 0
M2K_CURSOR_GLYPH EQU 01FH	; checkerboard

M2K_ESC: DB 0
M2K_ESC_ROW: DB 0

MSG_A:
	PUSH AF
	PUSH DE
	LD E,A
	CALL _SYS02
	POP DE
	POP AF
	RET
_SYS01:
	CALL FLGET
	CALL MSG_A
	RET
_SYS02:
	CALL CHKEY
	CP 3
	CALL Z,_BREAK
	JP PRINT
_SYS06:
	LD A,E
	INC A
	JP Z,INKEY
	JP PRINT
_SYS08:
	CALL FLGET
	CP 3
	CALL Z,_BREAK
	RET
_SYS0B:
CONSTX:
	CALL _FFLUSH
	CALL M2K_POLL_KEY
	JP Z,M2K_NO_KEY
	LD A,(_KEYD)
	OR A
	RET Z
	LD A,0FFH
	RET
_SYS2A:
_SYS2C:
	XOR A
	LD DE,0
	LD HL,0
	RET
FLGET:
	CALL _FFLUSH
	CALL INKEY
	RET NZ
	PUSH BC
	PUSH DE
	PUSH HL
	CALL M2K_CURSOR_ADDRESS
	LD B,H
	LD C,L
	CALL SCRN
	LD (M2K_CURSOR_CHAR),A
	LD A,1
	LD (M2K_CURSOR_VISIBLE),A
	LD A,M2K_CURSOR_GLYPH
	CALL M2K_PUT
	CALL M2K_TIMER_READ
	LD (M2K_CURSOR_TICK),HL

M2K_WAIT_KEY:
	CALL INKEY
	JR NZ,M2K_CURSOR_RESTORE
	CALL M2K_TIMER_READ
	EX DE,HL
	LD HL,(M2K_CURSOR_TICK)
	OR A
	SBC HL,DE			; elapsed ticks modulo 65536
	LD BC,15625			; half a second at 31.25 kHz
	OR A
	SBC HL,BC
	JR C,M2K_WAIT_KEY
	LD (M2K_CURSOR_TICK),DE
	LD A,(M2K_CURSOR_VISIBLE)
	XOR 1
	LD (M2K_CURSOR_VISIBLE),A
	LD A,M2K_CURSOR_GLYPH
	JR NZ,M2K_CURSOR_DRAW
	LD A,(M2K_CURSOR_CHAR)
M2K_CURSOR_DRAW:
	CALL M2K_CURSOR_PUT
	JR M2K_WAIT_KEY

M2K_CURSOR_RESTORE:
	PUSH AF
	LD A,(M2K_CURSOR_CHAR)
	CALL M2K_CURSOR_PUT
	POP AF
	POP HL
	POP DE
	POP BC
	RET

M2K_CURSOR_PUT:
	CALL M2K_CURSOR_ADDRESS
	JP M2K_PUT
M2K_CURSOR_ADDRESS:
	LD HL,(_TXADR)
	LD BC,TVRAM
	ADD HL,BC
	RET

M2K_CURSOR_CHAR: DB 0
M2K_CURSOR_VISIBLE: DB 0
M2K_CURSOR_TICK: DW 0

; BDOS 0Ah: DE -> capacity, count, then characters and terminating CR.
; Keep the write cursor in HL internally and preserve the caller's registers.
_SYS0A:
	PUSH BC
	PUSH DE
	PUSH HL
	EX DE,HL
	LD B,(HL)
	INC HL
	INC HL
	LD C,0
M2K_LINE_KEY:
	CALL _SYS08
	CP 0DH
	JR Z,M2K_LINE_END
	CP 8
	JR Z,M2K_LINE_DELETE
	CP 7FH
	JR Z,M2K_LINE_DELETE
	CP 20H
	JR C,M2K_LINE_KEY
	LD D,A
	LD A,C
	CP B
	JR NC,M2K_LINE_KEY
	LD A,D
	LD (HL),A
	INC HL
	INC C
	CALL MSG_A
	JR M2K_LINE_KEY
M2K_LINE_DELETE:
	LD A,C
	OR A
	JR Z,M2K_LINE_KEY
	DEC C
	DEC HL
	LD A,8
	CALL MSG_A
	LD A,' '
	CALL MSG_A
	LD A,8
	CALL MSG_A
	JR M2K_LINE_KEY
M2K_LINE_END:
	LD (HL),0DH
	POP HL
	POP DE
	INC DE
	LD A,C
	LD (DE),A
	DEC DE
	POP BC
	OR A
	RET

CONOUT1:
	LD E,C
	CALL PRINT
	LD A,E
	CP 0AH
	RET NZ
	LD E,0DH
	JP PRINT

PRINT:
	PUSH BC
	PUSH DE
	PUSH HL
	LD A,(M2K_ESC)
	OR A
	JR NZ,M2K_ESCAPE
	LD A,E
	CP 20H
	JR C,M2K_CONTROL
	LD HL,(_TXADR)
	LD BC,TVRAM
	ADD HL,BC
	CALL M2K_PUT
	CALL CTRL1C
	JR M2K_PRINT_END
M2K_CONTROL:
	ADD A,A
	LD L,A
	LD H,0
	LD BC,CTRLTB
	ADD HL,BC
	LD C,(HL)
	INC HL
	LD H,(HL)
	LD L,C
	CALL JPHL
	JR M2K_PRINT_END
M2K_ESCAPE:
	CP 2
	JR Z,M2K_ESCAPE_ROW
	CP 3
	JR Z,M2K_ESCAPE_COL
	XOR A
	LD (M2K_ESC),A
	LD A,E
	LD HL,M2K_ESC_TABLE
	LD B,M2K_ESC_COUNT
M2K_ESC_LOOKUP:
	CP (HL)
	INC HL
	JR Z,M2K_ESC_FOUND
	INC HL
	INC HL
	DJNZ M2K_ESC_LOOKUP
	JR M2K_PRINT_END
M2K_ESC_FOUND:
	LD A,(HL)
	INC HL
	LD H,(HL)
	LD L,A
	CALL JPHL
	JR M2K_PRINT_END
M2K_ESCAPE_ROW:
	LD A,E
	SUB 20H
	LD (M2K_ESC_ROW),A
	LD A,3
	LD (M2K_ESC),A
	JR M2K_PRINT_END
M2K_ESCAPE_COL:
	XOR A
	LD (M2K_ESC),A
	LD A,(M2K_ESC_ROW)
	LD H,A
	LD A,E
	SUB 20H
	LD L,A
	CALL LOC
M2K_PRINT_END:
	POP HL
	POP DE
	POP BC
	XOR A
	RET

M2K_ESCAPE_LOC:
	LD A,2
	LD (M2K_ESC),A
	RET
CTRL1B:
	LD A,1
	LD (M2K_ESC),A
	RET
CTRL00:
CTRL07:
CTRL12:
	RET
CTRL02:
CTRL08:
CTRL1D:
	LD HL,(_TXADR)
	LD A,H
	OR L
	RET Z
	DEC HL
	JR M2K_SET_POS
CTRL04:
	CALL POS
	LD A,L
	OR A
	RET Z
CTRL03:
	CALL CTRL0D
	JR CTRL0A
CTRL0D:
	CALL POS
	LD L,0
	JP LOC
CTRL09:
	LD HL,(_TXADR)
	LD A,L
	AND 0F8H
	LD L,A
	LD BC,8
	ADD HL,BC
	JR M2K_ADVANCE
CTRL0B:
	LD HL,0
	JR M2K_SET_POS
CTRL0C:
	CALL CTRL0B
CTRL06:
	LD DE,(_TXADR)
	LD HL,CELLS
	OR A
	SBC HL,DE
	LD B,H
	LD C,L
	JR M2K_CLEAR
CTRL05:
	CALL POS
	LD A,WIDTH
	SUB L
	LD C,A
	LD B,0
	LD DE,(_TXADR)
M2K_CLEAR:
	LD HL,TVRAM
	ADD HL,DE
	JP M2K_FILL
CTRL0E:
	CALL M2K_SCROLL
	JR CTRL1E
CTRL1C:
	LD HL,(_TXADR)
	INC HL
	JR M2K_ADVANCE
CTRL1E:
	LD HL,(_TXADR)
	LD BC,WIDTH
	OR A
	SBC HL,BC
	RET C
	JR M2K_SET_POS
CTRL0A:
CTRL1F:
	LD HL,(_TXADR)
	LD BC,WIDTH
	ADD HL,BC
M2K_ADVANCE:
	LD BC,CELLS
	OR A
	SBC HL,BC
	ADD HL,BC
	JR C,M2K_SET_POS
	PUSH HL
	CALL M2K_SCROLL
	POP HL
	LD BC,WIDTH
	OR A
	SBC HL,BC
M2K_SET_POS:
	LD (_TXADR),HL
	RET

; Return row in H, column in L. LOC accepts the same representation.
POS:
	PUSH BC
	LD HL,(_TXADR)
	LD BC,WIDTH
	XOR A
M2K_POS_LOOP:
	SBC HL,BC
	JR C,M2K_POS_END
	INC A
	JR M2K_POS_LOOP
M2K_POS_END:
	ADD HL,BC
	LD H,A
	POP BC
	OR A
	RET
LOC:
	PUSH AF
	PUSH BC
	PUSH HL
	LD A,L
	CP WIDTH
	JR NC,M2K_LOC_END
	LD A,H
	CP LINE
	JR NC,M2K_LOC_END
	LD H,0
	LD BC,WIDTH
	OR A
	JR Z,M2K_LOC_STORE
M2K_LOC_LOOP:
	ADD HL,BC
	DEC A
	JR NZ,M2K_LOC_LOOP
M2K_LOC_STORE:
	LD (_TXADR),HL
M2K_LOC_END:
	POP HL
	POP BC
	POP AF
	RET

INKEY:
	CALL M2K_POLL_KEY
	JR Z,M2K_NO_KEY
	LD (M2K_LAST_KEY),A
	LD A,(_KEYD)
	OR A
	RET
M2K_NO_KEY:
	XOR A
	RET

; A = matrix ID, NZ if the key has not been consumed by INKEY.
M2K_POLL_KEY:
	CALL CHKEY
	LD A,(M2K_KEY_ID)
	OR A
	JR NZ,M2K_COMPARE_KEY
	LD (M2K_LAST_KEY),A
	RET
M2K_COMPARE_KEY:
	PUSH HL
	LD HL,M2K_LAST_KEY
	CP (HL)
	POP HL
	RET
M2K_LAST_KEY: DB 0		; last consumed matrix ID
M2K_KEY_ID: DB 0		; selected matrix position + 1, or 0 if released
M2K_CAPS_LOCK: DB 0		; bit 2 inverts SHIFT for letters
M2K_CAPS_KEY_DOWN: DB 0		; bit 1 from keyboard row Bh

; A = row. Poll the PIO B input with interrupts disabled.
M2K_KEY_ROW:
	OR 10H
	LD B,A
	IN A,(PIO_A)
	AND 0E0H
	OR B
	OUT (PIO_A),A
	IN A,(PIO_B)
	CPL
	RET

CHKEY:
	DI
	PUSH BC
	PUSH DE
	PUSH HL
	LD A,0BH
	CALL M2K_KEY_ROW
	LD D,A
	AND 02H			; SFT LOCK toggles on the press edge
	LD HL,M2K_CAPS_KEY_DOWN
	CP (HL)
	JR Z,M2K_CAPS_READY
	LD (HL),A
	OR A
	JR Z,M2K_CAPS_READY
	LD A,(M2K_CAPS_LOCK)
	XOR 04H
	LD (M2K_CAPS_LOCK),A
M2K_CAPS_READY:
	LD E,0
	LD HL,M2K_KEYS
M2K_SCAN_ROW:
	LD A,E
	CALL M2K_KEY_ROW
	LD B,8
M2K_SCAN_BIT:
	RRCA
	JR NC,M2K_SCAN_NEXT
	LD C,A
	LD A,(HL)
	OR A
	JR NZ,M2K_KEY_FOUND
	LD A,C
M2K_SCAN_NEXT:
	INC HL
	DJNZ M2K_SCAN_BIT
	INC E
	LD A,E
	CP 0BH
	JR C,M2K_SCAN_ROW
	XOR A
	LD (M2K_KEY_ID),A
	JR M2K_KEY_RESULT
M2K_KEY_FOUND:
	LD C,A
	LD A,L
	SUB LOW M2K_KEYS
	INC A
	LD (M2K_KEY_ID),A
	LD A,C
	CP 'a'
	JR C,M2K_KEY_PUNCT
	CP 'z'+1
	JR NC,M2K_KEY_PUNCT
	BIT 0,D			; GRAPH with a letter selects the CP/M control code.
	JR NZ,M2K_KEY_CONTROL
	LD A,(M2K_CAPS_LOCK)
	XOR D
	AND 04H			; lowercase with SHIFT while Caps Lock is on
	LD A,C
	JR Z,M2K_KEY_RESULT
	AND 05FH
	JR M2K_KEY_RESULT
M2K_KEY_CONTROL:
	AND 01FH
	JR M2K_KEY_RESULT
M2K_KEY_PUNCT:
	BIT 2,D
	JR Z,M2K_KEY_RESULT
	LD BC,M2K_SHIFT_KEYS-M2K_KEYS
	ADD HL,BC
	LD A,(HL)
M2K_KEY_RESULT:
	LD (_KEYD),A
	POP HL
	POP DE
	POP BC
	OR A
	RET
