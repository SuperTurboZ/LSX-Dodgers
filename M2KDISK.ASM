; MB8876 programmed I/O, using the MZ-700 port's negative bus convention.
FDC_STATUS EQU 0D8H
FDC_TRACK EQU 0D9H
FDC_SECTOR EQU 0DAH
FDC_DATA EQU 0DBH
FDC_DRIVE EQU 0DCH
FDC_SIDE EQU 0DDH
PIT_COUNT0 EQU 0E4H
PIT_CONTROL EQU 0E7H
FDC_LIMIT EQU 0F000H

M2K_TIMER_INIT:
	LD A,34H			; channel 0, LSB/MSB, rate generator
	OUT (PIT_CONTROL),A
	XOR A
	OUT (PIT_COUNT0),A
	OUT (PIT_COUNT0),A		; modulus 65536
	OUT (0F0H),A			; trigger the timer gate
	RET

M2K_TIMER_READ:
	XOR A
	OUT (PIT_CONTROL),A		; latch channel 0
	IN A,(PIT_COUNT0)
	LD L,A
	IN A,(PIT_COUNT0)
	LD H,A
	RET
M2K_TIMER_START:
	PUSH HL
	CALL M2K_TIMER_READ
	LD (M2K_TIMER_BASE),HL
	POP HL
	RET
M2K_TIMER_EXPIRED:
	PUSH HL
	PUSH DE
	CALL M2K_TIMER_READ
	EX DE,HL
	LD HL,(M2K_TIMER_BASE)
	OR A
	SBC HL,DE			; unsigned elapsed ticks, including rollover
	LD A,H
	CP HIGH FDC_LIMIT
	CCF
	POP DE
	POP HL
	RET
M2K_TIMER_BASE: DW 0

M2K_FDC_READY:
	CALL M2K_TIMER_START
M2K_FDC_READY_LOOP:
	IN A,(FDC_STATUS)
	CPL
	AND 081H
	RET Z
	CALL M2K_TIMER_EXPIRED
	JR NC,M2K_FDC_READY_LOOP
	LD A,0D0H			; clear BUSY before retrying a timed-out command
	CALL M2K_FDC_COMMAND
	SCF
	RET
M2K_FDC_COMMAND:
	CPL
	OUT (FDC_STATUS),A
M2K_FDC_SETTLE:
	LD A,26			; about 0.1 ms at 4 MHz, as in M7DISK
M2K_FDC_SETTLE_LOOP:
	DEC A
	JR NZ,M2K_FDC_SETTLE_LOOP
	RET

; DE = LBA, IX = DPB. Return D = cylinder and E = sector ID.
M2K_FDC_SEEK:
	PUSH HL
	EX DE,HL
	LD C,(IX+DPB_MAXSEC)
	LD A,C
	OR A
	JR Z,M2K_FDC_BAD_GEOMETRY
	LD B,16
	XOR A
M2K_FDC_DIVIDE:
	ADD HL,HL
	ADC A,A
	CP C
	JR C,M2K_FDC_DIV_NEXT
	SUB C
	INC L
M2K_FDC_DIV_NEXT:
	DJNZ M2K_FDC_DIVIDE
	INC A
	LD E,A
	SRL L
	LD D,L
	SBC A,A
	LD C,A
	LD A,D
	CP (IX+DPB_MAXCYL)
	JR NC,M2K_FDC_BAD_GEOMETRY
	POP HL
	LD A,(_DRIVE)
	CP 4
	CCF
	RET C
	OR 84H
	OUT (FDC_DRIVE),A
	LD A,C
	OUT (FDC_SIDE),A
	CALL M2K_FDC_SETTLE
	CALL M2K_FDC_READY
	RET C
	LD A,(_DRIVE)
	LD C,A
	LD B,0
	LD HL,_CYL0
	ADD HL,BC
	LD A,(HL)
	INC A
	JR NZ,M2K_FDC_KNOWN
	LD C,08H			; Restore
	CALL M2K_FDC_TYPE1
	RET C
	AND 09CH			; Not Ready, Seek Error, CRC Error, Track 0
	XOR 04H			; do not cache cylinder 0 unless Track 0 is set
	SCF
	RET NZ
	LD (HL),0
M2K_FDC_KNOWN:
	LD A,(HL)
	CPL
	OUT (FDC_TRACK),A
	CPL
	CP D
	RET Z
	LD A,D
	CPL
	OUT (FDC_DATA),A
	LD C,18H			; Seek
	CALL M2K_FDC_TYPE1
	RET C
	AND 098H			; Not Ready, Seek Error, CRC Error
	SCF
	RET NZ
	LD (HL),D
	OR A
	RET
M2K_FDC_TYPE1:
	LD A,(_SEEKSP)
	AND 3
	OR C
	CALL M2K_FDC_COMMAND
	CALL M2K_FDC_READY
	RET C
	IN A,(FDC_STATUS)
	CPL
	RET
M2K_FDC_BAD_GEOMETRY:
	POP HL
	SCF
	RET

; On success advance both HL and DE, as the common disk layer expects.
FDRD:
	LD A,80H
	JR M2K_FDC_START
FDWT:
	LD A,0A0H
	JR M2K_FDC_START
WTTRK:
	LD A,0F4H
	LD B,1
M2K_FDC_START:
	PUSH BC
	LD C,A
	LD A,I
	DI
	LD A,C
	POP BC
	PUSH AF				; preserve the caller's interrupt state across retries
	LD (M2K_FDC_OP),A
	PUSH HL
	LD HL,M2K_FDC_READ
	BIT 5,A
	JR Z,M2K_FDC_SET_BYTE
	LD HL,M2K_FDC_WRITE
M2K_FDC_SET_BYTE:
	LD (M2K_FDC_BYTE_VECTOR),HL
	POP HL
M2K_FDC_NEXT:
	LD A,2
	LD (M2K_FDC_RETRY),A
M2K_FDC_ATTEMPT:
	PUSH BC
	PUSH DE
	PUSH HL
	CALL M2K_FDC_SEEK
	POP HL
	JP C,M2K_FDC_FAILED
	LD A,E
	CPL
	OUT (FDC_SECTOR),A
	PUSH HL
	LD B,(IX+DPB_BPS)
	RES 7,B
	LD C,0
	LD A,(M2K_FDC_OP)
	CP 0F4H
	JR NZ,M2K_FDC_RUN
	LD BC,6656			; upper bound for a 2D write-track stream
M2K_FDC_RUN:
	LD E,A
	LD A,B
	OR C
	JP Z,M2K_FDC_DATA_FAILED
	LD A,E
	CALL M2K_FDC_COMMAND
	; Test active-low DRQ and BUSY directly to shorten the polling loop.
M2K_FDC_POLL:
	IN A,(FDC_STATUS)
	RRCA
	RRCA
	JP NC,M2K_FDC_READ
M2K_FDC_BYTE_VECTOR EQU $-2
	BIT 6,A			; active-low BUSY after the two rotates
	JR Z,M2K_FDC_POLL
	JR M2K_FDC_DONE
M2K_FDC_READ:
	IN A,(FDC_DATA)
	CPL
	LD (HL),A
	JR M2K_FDC_BYTE_END
M2K_FDC_WRITE:
	LD A,(HL)
	CPL
	OUT (FDC_DATA),A
M2K_FDC_BYTE_END:
	INC HL
	DEC BC
	LD A,B
	OR C
	JR NZ,M2K_FDC_POLL

; The buffer is full. Wait for completion and reject an unexpected DRQ.
M2K_FDC_WAIT_END:
	IN A,(FDC_STATUS)
	RRCA
	RRCA
	JR NC,M2K_FDC_ABORT
	BIT 6,A
	JR Z,M2K_FDC_WAIT_END
M2K_FDC_DONE:
	RLCA
	RLCA
	CPL
	AND 0FCH
	JR NZ,M2K_FDC_DATA_FAILED
	LD A,E
	CP 0F4H
	JR Z,M2K_FDC_SUCCESS
	LD A,B
	OR C
	JR NZ,M2K_FDC_DATA_FAILED
M2K_FDC_SUCCESS:
	POP AF				; discard original buffer pointer
	POP DE
	POP BC
	INC DE
	DEC B
	JP NZ,M2K_FDC_NEXT
	CALL M2K_FDC_STOP
	POP AF
	JP PO,M2K_FDC_RETURN_OK
	EI
M2K_FDC_RETURN_OK:
	XOR A
	RET
M2K_FDC_ABORT:
	LD A,0D0H			; Force Interrupt (terminate command)
	CALL M2K_FDC_COMMAND
M2K_FDC_DATA_FAILED:
	POP HL
M2K_FDC_FAILED:
	POP DE
	POP BC
	PUSH HL
	PUSH DE
	LD A,(_DRIVE)
	CP 4
	JR NC,M2K_FDC_NO_CACHE
	LD E,A
	LD D,0
	LD HL,_CYL0
	ADD HL,DE
	LD (HL),0FFH
M2K_FDC_NO_CACHE:
	POP DE
	POP HL
	LD A,(M2K_FDC_RETRY)
	DEC A
	LD (M2K_FDC_RETRY),A
	JP NZ,M2K_FDC_ATTEMPT
	CALL M2K_FDC_STOP
	POP AF
	JP PO,M2K_FDC_RETURN_ERROR
	EI
M2K_FDC_RETURN_ERROR:
	LD A,0FFH
	OR A
	SCF
	RET
M2K_FDC_STOP:
	LD A,(_DRIVE)
	AND 3
	OUT (FDC_DRIVE),A
	RET
M2K_FDC_OP: DB 0
M2K_FDC_RETRY: DB 0
