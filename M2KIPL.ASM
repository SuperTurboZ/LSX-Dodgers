; SHARP MZ-2000 IPL BREAD reads from record zero to 8000h.
; After the normal-map reset the same sector begins at 0000h.
; CF14, CF1E are the byte count and ROM record number respectively.
MZT_HEADER_RAM EQU 01180H
MZT_PAYLOAD_RAM EQU MZT_HEADER_RAM+128
BOOT_STACK EQU 01180H
BOOT_TRACK EQU MZT_LBA/9
BOOT_SECTOR EQU MZT_LBA%9+1
BOOT_DRIVE EQU 07FECH		; IPL's FFEC drive byte after remap
	ORG 0
IPLPRO:
	DB 1,"IPLPRO","LSXDODGERS",0DH
	; The signature and name above decode as harmless register operations.
	; The +12h field is unused by the FDD IPL. Use it to reach our code.
	JR IPL_ENTRY
	DW 256,0,IPL_ENTRY,0,0,0
IPL_ENTRY:
	DI
	LD SP,BOOT_STACK
	LD A,(BOOT_DRIVE)
	AND 3
	OR 84H
	OUT (0DCH),A
	CALL IPL_READY
	LD HL,MZT_HEADER_RAM
	LD DE,BOOT_TRACK*256+BOOT_SECTOR
	LD A,MZT_SECTORS
	EX AF,AF'
IPL_TRACK:
	LD A,D
	AND 1
	OUT (0DDH),A
	LD A,D
	SRL A
	CPL
	OUT (0DBH),A
	LD A,0E7H		; inverted SEEK 18h
	CALL IPL_COMMAND
	CALL IPL_READY
IPL_SECTOR:
	LD A,E
	CPL
	OUT (0DAH),A
	LD A,07FH		; inverted READ SECTOR 80h
	CALL IPL_COMMAND
	LD BC,512
	LD IX,0
IPL_DATA:
	IN A,(0D8H)
	RRCA
	JR C,IPL_SECTOR_DONE
	RRCA
	JR NC,IPL_BYTE
	DEC IX
	LD A,IXH
	OR IXL
	JR NZ,IPL_DATA
	JR IPL_ERROR
IPL_BYTE:
	LD A,B
	OR C
	JR Z,IPL_ERROR
	IN A,(0DBH)
	CPL
	LD (HL),A
	INC HL
	DEC BC
	JR IPL_DATA
IPL_SECTOR_DONE:
	CPL
	AND 04FH
	JR NZ,IPL_ERROR
	LD A,B
	OR C
	JR NZ,IPL_ERROR
	EX AF,AF'
	DEC A
	JR Z,IPL_CHECK_MZT
	EX AF,AF'
	INC E
	LD A,E
	CP 10
	JR C,IPL_SECTOR
	LD E,1
	INC D
	JR IPL_TRACK
IPL_CHECK_MZT:
	CALL IPL_STOP_MOTOR
	LD A,(MZT_HEADER_RAM)
	CP 1
	JR NZ,IPL_ERROR
	LD HL,(MZT_HEADER_RAM+18)
	LD DE,MZT_PAYLOAD_BYTES
	OR A
	SBC HL,DE
	JR NZ,IPL_ERROR
	LD HL,(MZT_HEADER_RAM+20)
	LD DE,MZT_PAYLOAD_RAM
	SBC HL,DE
	JR NZ,IPL_ERROR
	LD HL,(MZT_HEADER_RAM+22)
	SBC HL,DE
	JR NZ,IPL_ERROR
	JP MZT_PAYLOAD_RAM
IPL_COMMAND:
	OUT (0D8H),A
	NOP
	NOP
	NOP
	NOP
	RET
IPL_READY:
	LD BC,0
IPL_READY_POLL:
	IN A,(0D8H)
	CPL
	AND 081H
	RET Z
	DEC BC
	LD A,B
	OR C
	JR NZ,IPL_READY_POLL
IPL_ERROR:
	LD A,02FH		; terminate the command
	OUT (0D8H),A
	CALL IPL_STOP_MOTOR
	HALT
	JR IPL_ERROR
IPL_STOP_MOTOR:
	LD A,(BOOT_DRIVE)
	AND 3
	OUT (0DCH),A
	RET
IPL_END:
	DS 255-($-IPLPRO)
	DB 0
	END
