; Call with interrupts disabled. Preserve the unrelated port A bits.
M2K_MAP:
	IN A,(PIO_A)
	AND 03FH
	OR C
	OUT (PIO_A),A
	RET

M2K_GRAM_BEGIN:
	OUT (GRAM_PAGE),A
	LD C,080H
	JR M2K_MAP
M2K_GRAM_END:
	LD C,0
	CALL M2K_MAP
	XOR A
	OUT (GRAM_PAGE),A
	RET

; HL = main RAM, DE = first sector, B = sector count (0 means 256).
GDRD:
	XOR A
	JR M2K_GRAM_TRANSFER
GDWT:
	LD A,1
M2K_GRAM_TRANSFER:
	DI
	LD (M2K_GRAM_WRITE),A
	LD (M2K_SAVED_SP),SP
	LD SP,M2K_GRAM_STACK_END
M2K_GRAM_NEXT:
	LD A,D
	OR A
	JR NZ,M2K_GRAM_ERROR
	LD A,E
	CP 192
	JR NC,M2K_GRAM_ERROR
	PUSH BC
	PUSH DE
	PUSH HL
	RLCA
	RLCA
	AND 3
	INC A
	LD (M2K_GRAM_BANK),A
	LD A,E
	OR 0C0H
	LD D,A
	LD E,0
	PUSH DE
	LD A,(M2K_GRAM_WRITE)
	OR A
	JR Z,M2K_GRAM_READ
	LD DE,M2K_GRAM_BUFFER
	LD BC,256
	LDIR
	LD A,(M2K_GRAM_BANK)
	CALL M2K_GRAM_BEGIN
	POP DE
	LD HL,M2K_GRAM_BUFFER
	LD BC,256
	LDIR
	CALL M2K_GRAM_END
	POP HL
	INC H
	JR M2K_GRAM_ADVANCE
M2K_GRAM_READ:
	LD A,(M2K_GRAM_BANK)
	CALL M2K_GRAM_BEGIN
	POP HL
	LD DE,M2K_GRAM_BUFFER
	LD BC,256
	LDIR
	CALL M2K_GRAM_END
	POP DE
	LD HL,M2K_GRAM_BUFFER
	LD BC,256
	LDIR
	EX DE,HL
M2K_GRAM_ADVANCE:
	POP DE
	POP BC
	INC DE
	DJNZ M2K_GRAM_NEXT
	XOR A
	JR M2K_GRAM_RETURN
M2K_GRAM_ERROR:
	LD A,0FFH
	SCF
M2K_GRAM_RETURN:
	LD SP,(M2K_SAVED_SP)
	RET

; Save all three bytes before writing any pattern. Distinct patterns
; detect aliased pages. Restore the original bytes before leaving.
M2K_GRAM_PROBE:
	LD (M2K_SAVED_SP),SP
	LD SP,M2K_GRAM_STACK_END
	LD HL,M2K_GRAM_ORIGINAL
	LD B,1
M2K_GRAM_SAVE:
	LD A,B
	CALL M2K_GRAM_BEGIN
	LD A,(0C000H)
	LD (HL),A
	INC HL
	INC B
	LD A,B
	CP 4
	JR C,M2K_GRAM_SAVE
	LD B,1
M2K_GRAM_MARK:
	LD A,B
	CALL M2K_GRAM_BEGIN
	LD A,B
	XOR 0A4H
	LD (0C000H),A
	INC B
	LD A,B
	CP 4
	JR C,M2K_GRAM_MARK
	LD D,2
	LD B,1
M2K_GRAM_CHECK:
	LD A,B
	CALL M2K_GRAM_BEGIN
	LD A,(0C000H)
	XOR 0A4H
	CP B
	JR Z,M2K_GRAM_CHECK_NEXT
	LD D,0
M2K_GRAM_CHECK_NEXT:
	INC B
	LD A,B
	CP 4
	JR C,M2K_GRAM_CHECK
	LD HL,M2K_GRAM_ORIGINAL
	LD B,1
M2K_GRAM_RESTORE:
	LD A,B
	CALL M2K_GRAM_BEGIN
	LD A,(HL)
	LD (0C000H),A
	INC HL
	INC B
	LD A,B
	CP 4
	JR C,M2K_GRAM_RESTORE
	CALL M2K_GRAM_END
	LD A,D
	LD (GRAMFL),A
	LD SP,(M2K_SAVED_SP)
	RET

M2K_GRAM_WRITE:	DB 0
M2K_GRAM_BANK:	DB 0
M2K_GRAM_ORIGINAL: DS 3
M2K_SAVED_SP:	DW 0
M2K_GRAM_BUFFER: DS 256
M2K_GRAM_STACK:	DS 32
M2K_GRAM_STACK_END:
M2K_GRAM_SAFE_END:
