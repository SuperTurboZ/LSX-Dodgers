; Two seven-byte routines copied into page zero at startup.
; A = GRAM map, C = normal map, HL = GRAM address. B holds the data.
M2K_GRAM_CODE EQU 0040H
M2K_GRAM_READ_BYTE EQU M2K_GRAM_CODE
M2K_GRAM_WRITE_BYTE EQU M2K_GRAM_CODE+M2K_GRAM_WRITE_IMAGE-M2K_GRAM_CODE_IMAGE
M2K_GRAM_CODE_IMAGE:
	OUT (PIO_A),A
	LD B,(HL)
	LD A,C
	OUT (PIO_A),A
	RET
M2K_GRAM_WRITE_IMAGE:
	OUT (PIO_A),A
	LD (HL),B
	LD A,C
	OUT (PIO_A),A
	RET
M2K_GRAM_CODE_END:

; Disk driver entry: HL = RAM buffer, C:DE = sector, B = count.
GDRD:
	XOR A
	JR M2K_GRAM_TRANSFER
GDWT:
	LD A,1
M2K_GRAM_TRANSFER:
	LD (M2K_RAM_WRITE),A
	PUSH IX
	LD IX,M2K_GRAM_SECTORS
	CALL M2K_RAM_RANGE
	POP IX
	JP C,M2K_RAM_ERROR
	LD A,I
	DI
	PUSH AF

M2K_GRAM_NEXT:
	PUSH BC
	PUSH DE
	LD A,E
	RLCA
	RLCA
	RLCA
	AND 7
	INC A
	OUT (GRAM_PAGE),A
	LD A,E
	AND 01FH
	ADD A,A
	OR 0C0H
	EX DE,HL
	LD H,A
	LD L,0
	IN A,(PIO_A)
	AND 03FH
	LD C,A

M2K_GRAM_BYTE:
	LD A,(M2K_RAM_WRITE)
	OR A
	JR NZ,M2K_GRAM_WRITE
	LD A,C
	OR 080H
	CALL M2K_GRAM_READ_BYTE
	LD A,B
	LD (DE),A
	JR M2K_GRAM_ADVANCE
M2K_GRAM_WRITE:
	LD A,(DE)
	LD B,A
	LD A,C
	OR 080H
	CALL M2K_GRAM_WRITE_BYTE
M2K_GRAM_ADVANCE:
	INC DE
	INC HL
	LD A,L
	OR A
	JR NZ,M2K_GRAM_BYTE
	BIT 0,H
	JR NZ,M2K_GRAM_BYTE		; stop at the next 512-byte boundary

	XOR A
	OUT (GRAM_PAGE),A
	EX DE,HL
	POP DE
	INC DE
	POP BC
	DJNZ M2K_GRAM_NEXT
	JR M2K_RAM_DONE

; The PIO-3034 address counter increments after either data operation.
EDRD:
	XOR A
	JR M2K_EMM_TRANSFER
EDWT:
	LD A,1
M2K_EMM_TRANSFER:
	LD (M2K_RAM_WRITE),A
	PUSH IX
	LD IX,M2K_EMM_SECTORS
	CALL M2K_RAM_RANGE
	POP IX
	JR C,M2K_RAM_ERROR
	LD A,I
	DI
	PUSH AF
	PUSH BC
	PUSH DE
	SLA E
	RL D
	LD C,D
	LD D,E
	LD E,0
	CALL M2K_EMM_ADDR
	POP DE
	POP BC

M2K_EMM_NEXT:
	PUSH BC
	LD BC,M2K_EMM_DATA
	LD A,(M2K_RAM_WRITE)
	OR A
	JR NZ,M2K_EMM_WRITE
	INIR
	INIR
	JR M2K_EMM_ADVANCE
M2K_EMM_WRITE:
	OTIR
	OTIR
M2K_EMM_ADVANCE:
	INC DE
	POP BC
	DJNZ M2K_EMM_NEXT

M2K_RAM_DONE:
	POP AF
	JP PO,M2K_RAM_SUCCESS
	EI
M2K_RAM_SUCCESS:
	XOR A
	RET
M2K_RAM_ERROR:
	LD A,0FFH
	SCF
	RET

; IX = device sector count. Check the complete request before any I/O.
M2K_RAM_RANGE:
	LD A,C
	OR A
	JR NZ,M2K_RAM_ERROR
	LD A,B
	DEC A
	CP 128				; 1..128 sectors fit in a 64 KiB address space
	JR NC,M2K_RAM_ERROR
	LD A,H
	OR A
	JR NZ,M2K_RAM_SECTORS
	LD A,L
	CP 050H			; a 512-byte span starting below this can hit GRAM code
	JR C,M2K_RAM_ERROR
M2K_RAM_SECTORS:
	PUSH HL
	PUSH BC
	LD C,B
	LD B,0
	PUSH IX
	POP HL
	OR A
	SBC HL,DE
	JR C,M2K_RAM_RANGE_END
	SBC HL,BC
M2K_RAM_RANGE_END:
	POP BC
	POP HL
	RET C
	PUSH HL
	PUSH DE
	LD A,B
	ADD A,A
	DEC A
	LD D,A
	LD E,0FFH			; last byte offset = count * 512 - 1
	ADD HL,DE
	POP DE
	POP HL
	RET

; C:DE = byte address.
M2K_EMM_ADDR:
	LD A,E
	OUT (M2K_EMM_LOW),A
	LD A,D
	OUT (M2K_EMM_MID),A
	LD A,C
	OUT (M2K_EMM_HIGH),A
	RET

; Read all original bytes before writing patterns, then restore them.
M2K_GRAM_PROBE:
	PUSH IX
	LD IX,M2K_GRAM_ORIGINAL
	LD HL,0C000H
	IN A,(PIO_A)
	AND 03FH
	LD C,A
	LD D,1
M2K_GRAM_SAVE:
	CALL M2K_GRAM_PROBE_PAGE
	CALL M2K_GRAM_READ_BYTE
	LD (IX+0),B
	INC IX
	INC D
	LD A,D
	CP 4
	JR C,M2K_GRAM_SAVE
	LD D,1
M2K_GRAM_MARK:
	LD A,D
	XOR 0A4H
	LD B,A
	CALL M2K_GRAM_PROBE_PAGE
	CALL M2K_GRAM_WRITE_BYTE
	INC D
	LD A,D
	CP 4
	JR C,M2K_GRAM_MARK
	LD D,1
	LD E,M2K_GRAM_FAT_SECTORS
M2K_GRAM_CHECK:
	CALL M2K_GRAM_PROBE_PAGE
	CALL M2K_GRAM_READ_BYTE
	LD A,D
	XOR 0A4H
	CP B
	JR Z,M2K_GRAM_CHECK_NEXT
	LD E,0
M2K_GRAM_CHECK_NEXT:
	INC D
	LD A,D
	CP 4
	JR C,M2K_GRAM_CHECK
	LD D,1
	LD IX,M2K_GRAM_ORIGINAL
M2K_GRAM_RESTORE:
	LD B,(IX+0)
	CALL M2K_GRAM_PROBE_PAGE
	CALL M2K_GRAM_WRITE_BYTE
	INC IX
	INC D
	LD A,D
	CP 4
	JR C,M2K_GRAM_RESTORE
	XOR A
	OUT (GRAM_PAGE),A
	LD A,E
	LD (GRAMFL),A
	POP IX
	RET

M2K_GRAM_PROBE_PAGE:
	LD A,D
	OUT (GRAM_PAGE),A
	LD A,C
	OR 080H
	RET

; Save a byte in each 64 KiB bank and verify that the banks are distinct.
M2K_EMM_PROBE:
	LD DE,0FFFFH
	LD HL,M2K_EMM_ORIGINAL
	LD C,0
M2K_EMM_SAVE:
	CALL M2K_EMM_ADDR
	IN A,(M2K_EMM_DATA)
	LD (HL),A
	INC HL
	INC C
	LD A,C
	CP 5
	JR C,M2K_EMM_SAVE
	LD C,0
M2K_EMM_MARK:
	CALL M2K_EMM_ADDR
	LD A,C
	XOR 0A4H
	OUT (M2K_EMM_DATA),A
	INC C
	LD A,C
	CP 5
	JR C,M2K_EMM_MARK
	LD C,0
	LD B,M2K_EMM_FAT_SECTORS
M2K_EMM_CHECK:
	CALL M2K_EMM_ADDR
	IN A,(M2K_EMM_DATA)
	XOR C
	CP 0A4H
	JR Z,M2K_EMM_CHECK_NEXT
	LD B,0
M2K_EMM_CHECK_NEXT:
	INC C
	LD A,C
	CP 5
	JR C,M2K_EMM_CHECK
	LD C,0
	LD HL,M2K_EMM_ORIGINAL
M2K_EMM_RESTORE:
	CALL M2K_EMM_ADDR
	LD A,(HL)
	OUT (M2K_EMM_DATA),A
	INC HL
	INC C
	LD A,C
	CP 5
	JR C,M2K_EMM_RESTORE
	LD A,B
	LD (EMMFL),A
	RET

M2K_RAM_WRITE: DB 0
M2K_GRAM_ORIGINAL: DS 3
M2K_EMM_ORIGINAL: DS 5
